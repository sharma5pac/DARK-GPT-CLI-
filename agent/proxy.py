"""Optional local HTTP proxy capture for DarkGPT.

Integrates with mitmdump (mitmproxy) when installed. Captures HTTP flows to
JSONL per target and can import endpoints/params into the knowledge graph.
Designed as additive - if mitmproxy is unavailable, tool returns actionable error.
"""

from __future__ import annotations

import asyncio
import json
import os
import shutil
import signal
import time
from pathlib import Path
from typing import Any, Dict, List, Optional
from urllib.parse import urlparse, parse_qs

from agent import knowledge_graph as kg

PROXY_ROOT = Path.home() / ".cache" / "darkgpt" / "proxy"


def _target_dir(target: str) -> Path:
    d = PROXY_ROOT / kg.slugify(target or "default")
    d.mkdir(parents=True, exist_ok=True)
    return d


def _addon_path(target: str) -> Path:
    d = _target_dir(target)
    p = d / "capture_addon.py"
    flow_log = d / "flows.jsonl"
    p.write_text(f'''# auto generated by DarkGPT
import json, time
from mitmproxy import http
LOG = r"{flow_log}"
def response(flow: http.HTTPFlow):
    try:
        req = flow.request; res = flow.response
        entry = {{
            "ts": time.time(),
            "method": req.method,
            "url": req.pretty_url,
            "host": req.host,
            "path": req.path,
            "status": res.status_code if res else None,
            "req_headers": dict(req.headers),
            "res_headers": dict(res.headers) if res else {{}},
            "req_content_type": req.headers.get("content-type",""),
            "res_content_type": res.headers.get("content-type","") if res else "",
            "req_size": len(req.raw_content or b""),
            "res_size": len(res.raw_content or b"") if res else 0,
        }}
        # redact obvious auth
        for h in ("authorization","cookie","set-cookie","proxy-authorization"):
            if h in entry["req_headers"]: entry["req_headers"][h] = "[REDACTED]"
            if h in entry["res_headers"]: entry["res_headers"][h] = "[REDACTED]"
        with open(LOG, "a", encoding="utf-8") as f:
            f.write(json.dumps(entry, ensure_ascii=False) + "\\n")
    except Exception:
        pass
''', encoding="utf-8")
    return p


class ProxyManager:
    def __init__(self) -> None:
        self.proc: Optional[asyncio.subprocess.Process] = None
        self.target = ""
        self.port = 0
        self.log_path: Optional[Path] = None

    async def start(self, target: str, port: int = 8080) -> Dict[str, Any]:
        if self.proc and self.proc.returncode is None:
            return {"ok": True, "status": "already_running", "target": self.target, "port": self.port, "log_path": str(self.log_path)}
        exe = shutil.which("mitmdump") or shutil.which("mitmproxy")
        if not exe:
            return {"ok": False, "error": "mitmdump/mitmproxy not installed. Install with: pip install mitmproxy (or apt package), then retry."}
        d = _target_dir(target)
        addon = _addon_path(target)
        self.log_path = d / "flows.jsonl"
        cmd = [exe, "-s", str(addon), "-p", str(int(port)), "--set", "stream_large_bodies=1m", "--quiet"]
        self.proc = await asyncio.create_subprocess_exec(*cmd, stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.STDOUT, cwd=str(d))
        self.target = target
        self.port = int(port)
        await asyncio.sleep(1.0)
        if self.proc.returncode is not None:
            out = b""
            try:
                if self.proc.stdout:
                    out = await asyncio.wait_for(self.proc.stdout.read(4000), timeout=1)
            except Exception:
                pass
            return {"ok": False, "error": f"proxy exited early: {out.decode('utf-8',errors='replace')[:500]}"}
        return {"ok": True, "status": "running", "target": target, "port": self.port, "log_path": str(self.log_path), "pid": self.proc.pid}

    async def stop(self) -> Dict[str, Any]:
        if not self.proc:
            return {"ok": True, "status": "not_running"}
        proc = self.proc
        self.proc = None
        if proc.returncode is None:
            try:
                proc.terminate()
                await asyncio.wait_for(proc.wait(), timeout=5)
            except Exception:
                try:
                    proc.kill()
                except Exception:
                    pass
        return {"ok": True, "status": "stopped"}

    def status(self) -> Dict[str, Any]:
        running = bool(self.proc and self.proc.returncode is None)
        flows = 0
        if self.log_path and self.log_path.exists():
            try:
                flows = sum(1 for _ in self.log_path.open("r", encoding="utf-8", errors="replace"))
            except Exception:
                pass
        return {"ok": True, "running": running, "target": self.target, "port": self.port, "log_path": str(self.log_path) if self.log_path else None, "flows_captured": flows}

    def export_to_graph(self, target: str = "", limit: int = 500) -> Dict[str, Any]:
        target = target or self.target
        if not target:
            return {"ok": False, "error": "no target"}
        lp = _target_dir(target) / "flows.jsonl"
        if not lp.exists():
            return {"ok": False, "error": f"no flow log: {lp}"}
        counts = {"endpoints": 0, "params": 0}
        lines = lp.read_text(encoding="utf-8", errors="replace").splitlines()[-limit:]
        for line in lines:
            try:
                e = json.loads(line)
            except Exception:
                continue
            url = str(e.get("url") or "")
            if not url.startswith(("http://", "https://")):
                continue
            attrs = {"method": e.get("method"), "status": e.get("status"), "seen_via": "proxy"}
            kg.add_endpoint(target, url.split("?")[0], attrs, source="proxy")
            counts["endpoints"] += 1
            try:
                qs = parse_qs(urlparse(url).query)
                for name in qs.keys():
                    kg.add_param(target, url.split("?")[0], name, "query", {"seen_via": "proxy"}, source="proxy")
                    counts["params"] += 1
            except Exception:
                pass
        return {"ok": True, "target": target, "imported": counts, "log_path": str(lp)}
